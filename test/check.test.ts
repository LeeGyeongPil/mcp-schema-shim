import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { check, PROFILES, PROFILE_IDS } from "../src/index.js";
import { FIXTURES, loadFixture } from "./helpers/mock-model.js";

const pointers = (diags: { ruleId: string; pointer: string }[], ruleId: string): string[] =>
  diags.filter((d) => d.ruleId === ruleId).map((d) => d.pointer).sort();

describe("check", () => {
  const tool = loadFixture("sdk-v1-tools").find((t) => t.name === "search_issues")!;

  // AC-1
  it("detects probe findings per profile", () => {
    const gemini = check(tool, "gemini-parameters");
    expect(pointers(gemini, "gemini-parameters/meta-keyword")).toEqual(["/$schema"]);
    expect(pointers(gemini, "gemini-parameters/const")).toEqual(["/properties/state/const"]);
    expect(pointers(gemini, "gemini-parameters/type-array")).toEqual(["/properties/filters/items/properties/value/type"]);

    const openai = check(tool, "openai-strict");
    expect(pointers(openai, "openai-strict/additional-properties")).toEqual(
      ["/additionalProperties", "/properties/filters/items/additionalProperties", "/properties/sort/additionalProperties"].sort(),
    );
    expect(pointers(openai, "openai-strict/optional-property")).toEqual(
      ["/properties/limit", "/properties/state", "/properties/since", "/properties/filters", "/properties/sort"].sort(),
    );
    // integer is supported by OpenAI strict mode: no false positive.
    expect(openai.filter((d) => d.pointer.endsWith("/limit/type") || d.message.includes("integer"))).toEqual([]);

    const anthropic = check(tool, "anthropic-strict");
    expect(pointers(anthropic, "anthropic-strict/unsupported-constraint")).toEqual(
      ["/properties/query/minLength", "/properties/limit/minimum", "/properties/limit/maximum"].sort(),
    );
    // The long date-time pattern generated by zod is flagged as too complex.
    expect(pointers(anthropic, "anthropic-strict/complex-pattern")).toEqual(["/properties/since/pattern"]);
  });

  it("treats the two Gemini paths differently", () => {
    const jsonSchema = check(tool, "gemini-json-schema");
    expect(jsonSchema.filter((d) => d.severity === "error")).toEqual([]);
    expect(pointers(jsonSchema, "gemini-json-schema/ignored-keyword")).toEqual(["/properties/query/minLength"]);
  });

  // AC-2
  it("every rule has an official docUrl and is documented", () => {
    const allowedHosts = ["developers.openai.com", "aistudio.google.com", "ai.google.dev", "platform.claude.com"];
    const ids: string[] = [];
    for (const id of PROFILE_IDS) {
      expect(PROFILES[id].rules.length).toBeGreaterThan(0);
      for (const rule of PROFILES[id].rules) {
        ids.push(rule.id);
        expect(rule.id.startsWith(id + "/")).toBe(true);
        expect(allowedHosts).toContain(new URL(rule.docUrl).host);
        expect(rule.summary.length).toBeGreaterThan(10);
      }
    }
    const doc = readFileSync(new URL("../docs/rules.md", import.meta.url), "utf8");
    const documented = [...doc.matchAll(/^\| `([a-z-]+\/[a-z-]+)` \|/gm)].map((m) => m[1]);
    expect([...documented].sort()).toEqual([...ids].sort());
  });

  it("every emitted diagnostic is complete and refers to a registered rule", () => {
    const registered = new Set(PROFILE_IDS.flatMap((p) => PROFILES[p].rules.map((r) => r.id)));
    for (const f of FIXTURES) {
      for (const profile of PROFILE_IDS) {
        for (const d of check(loadFixture(f), profile)) {
          expect(registered.has(d.ruleId)).toBe(true);
          expect(d.tool).not.toBe("");
          expect(d.docUrl).toMatch(/^https:\/\//);
          expect(["error", "warning", "info"]).toContain(d.severity);
          expect(typeof d.fixable).toBe("boolean");
          expect(d.pointer === "" || d.pointer.startsWith("/")).toBe(true);
        }
      }
    }
  });

  it("explains bad input and how to fix it", () => {
    expect(() => check({ name: "x" } as never, "openai-strict")).toThrow(/inputSchema/);
    expect(() => check({ inputSchema: {} } as never, "openai-strict")).toThrow(/name/);
    expect(() => check(tool, "nope" as never)).toThrow(/Choose one of: gemini-parameters/);
  });
});
